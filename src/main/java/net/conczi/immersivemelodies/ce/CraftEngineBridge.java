package net.conczi.immersivemelodies.ce;

import net.conczi.immersivemelodies.ImmersiveMelodiesPlugin;
import org.bukkit.Bukkit;

import java.io.File;
import java.io.FileOutputStream;
import java.io.OutputStreamWriter;
import java.io.Writer;
import java.nio.charset.StandardCharsets;

/**
 * CraftEngine 软依赖桥接：
 * - 检测 CraftEngine 是否加载
 * - 生成 CE 物品配置文件（11 种乐器）
 */
public class CraftEngineBridge {

    private final ImmersiveMelodiesPlugin plugin;
    private boolean craftEnginePresent = false;

    public CraftEngineBridge(ImmersiveMelodiesPlugin plugin) {
        this.plugin = plugin;
    }

    public void setup() {
        craftEnginePresent = Bukkit.getPluginManager().isPluginEnabled("CraftEngine");
        if (craftEnginePresent) {
            plugin.getLogger().info("检测到 CraftEngine，正在注入乐器配置...");
            generateInstrumentConfig();
            generateGuiItemConfig();
        }
    }

    public boolean isCraftEnginePresent() {
        return craftEnginePresent && CeApi.available();
    }

    /**
     * 通过 CE API 构建乐器物品（真实 CE 注册物品）。
     * CE 中尚未加载（如需 /ce reload）时返回 null，由调用方回退。
     */
    public org.bukkit.inventory.ItemStack buildInstrumentItem(String instrumentId) {
        if (!isCraftEnginePresent()) return null;
        return CeApi.buildItem(instrumentId);
    }

    /**
     * 通过 CE API 反查物品对应的乐器 ID。
     */
    public String detectInstrumentId(org.bukkit.inventory.ItemStack stack) {
        if (!isCraftEnginePresent()) return null;
        return CeApi.itemIdOf(stack);
    }

    /**
     * 在 plugins/CraftEngine/resources/immersive_melodies/configuration/instruments.yml 生成乐器定义。
     */
    private void generateInstrumentConfig() {
        File cePluginDir = new File(plugin.getDataFolder().getParentFile(), "CraftEngine");
        if (!cePluginDir.isDirectory()) {
            return;
        }
        // CE 标准布局: resources/<pack>/configuration/*.yml
        File targetDir = new File(cePluginDir, "resources/immersive_melodies/configuration");
        //noinspection ResultOfMethodCallIgnored
        targetDir.mkdirs();

        File configFile = new File(targetDir, "instruments.yml");
        try (Writer w = new OutputStreamWriter(new FileOutputStream(configFile), StandardCharsets.UTF_8)) {
            w.write("# Auto-generated by ImmersiveMelodiesFolia for CraftEngine\n");
            w.write("# GUI 用 icon 平面图标，手持用 3D Blockbench 模型，创造栏 equipment 分类可搜索\n\n");
            w.write("items:\n");

            String[] instruments = {"bagpipe", "didgeridoo", "flute", "lute", "piano", "triangle",
                    "trumpet", "tiny_drum", "vielle", "ender_bass", "handpan"};

            for (String id : instruments) {
                w.write(String.format("  immersive_melodies:%s:\n", id));
                w.write("    material: paper\n");
                w.write("    category: equipment\n");
                w.write("    data:\n");
                w.write(String.format("      item-name: <!i><lang:item.immersive_melodies.%s>\n", id));
                w.write("      max-stack-size: 1\n");
                w.write("    model:\n");
                w.write("      type: minecraft:select\n");
                w.write("      property: minecraft:display_context\n");
                w.write("      cases:\n");
                w.write("        - when: [gui, fixed, ground]\n");
                w.write("          model:\n");
                w.write("            type: minecraft:model\n");
                w.write(String.format("            path: immersive_melodies:item/%s\n", id));
                w.write("      fallback:\n");
                w.write("        type: minecraft:model\n");
                w.write(String.format("        path: immersive_melodies:item/%s_hand\n", id));
            }
            plugin.getLogger().info("CraftEngine 配置已写入: " + configFile.getAbsolutePath());
        } catch (Exception e) {
            plugin.getLogger().warning("生成 CraftEngine 配置失败: " + e.getMessage());
        }
    }

    /**
     * GUI 物品显示名使用的语言键（与原模组 zh_cn/en_us 的翻译一致）。
     * 贴图/模型清单以 {@link net.conczi.immersivemelodies.text.TextAssetGenerator#GUI_ICONS} 为唯一来源。
     */
    private static String langKey(String iconId) {
        return switch (iconId) {
            case "close" -> "immersive_melodies.close";
            case "tracks" -> "immersive_melodies.tracks";
            case "keyboard" -> "immersive_melodies.keyboard";
            case "pause" -> "immersive_melodies.pause";
            case "play" -> "immersive_melodies.play";
            case "delete" -> "immersive_melodies.delete";
            case "upload" -> "immersive_melodies.upload";
            case "help" -> "immersive_melodies.help";
            case "page_up" -> "gui.immersive_melodies.prev_page";
            case "page_down" -> "gui.immersive_melodies.next_page";
            default -> null;
        };
    }

    /**
     * 在 plugins/CraftEngine/resources/immersive_melodies/configuration/gui_items.yml 生成 GUI 按钮物品定义。
     * 贴图与模型 json 由 TextAssetGenerator 运行时裁剪生成到 resourcepack 目录。
     */
    private void generateGuiItemConfig() {
        File cePluginDir = new File(plugin.getDataFolder().getParentFile(), "CraftEngine");
        if (!cePluginDir.isDirectory()) {
            return;
        }
        File targetDir = new File(cePluginDir, "resources/immersive_melodies/configuration");
        //noinspection ResultOfMethodCallIgnored
        targetDir.mkdirs();

        File configFile = new File(targetDir, "gui_items.yml");
        try (Writer w = new OutputStreamWriter(new FileOutputStream(configFile), StandardCharsets.UTF_8)) {
            w.write("# Auto-generated by ImmersiveMelodiesFolia for CraftEngine\n");
            w.write("# 乐谱 GUI 按钮物品（贴图由插件运行时从 paper.png 裁剪生成到 resourcepack textures/gui/）\n\n");
            w.write("items:\n");

            for (net.conczi.immersivemelodies.text.TextAssetGenerator.GuiIcon icon
                    : net.conczi.immersivemelodies.text.TextAssetGenerator.GUI_ICONS) {
                writeGuiItem(w, icon.id(), "immersive_melodies:gui/btn_" + icon.id(), langKey(icon.id()));
            }
            // 自由演奏界面的退出按钮：原模组该处使用红色 X（与删除同图），tooltip 仍为“关闭”
            writeGuiItem(w, "exit", "immersive_melodies:gui/btn_delete", "immersive_melodies.close");
            // blank 使用空模型 empty.json，作为歌曲行的不可见点击区
            writeGuiItem(w, "blank", "immersive_melodies:gui/empty", null);

            plugin.getLogger().info("CraftEngine GUI 物品配置已写入: " + configFile.getAbsolutePath());
        } catch (Exception e) {
            plugin.getLogger().warning("生成 CraftEngine GUI 物品配置失败: " + e.getMessage());
        }
    }

    /** 写一个 GUI 按钮 CE 物品；langKey 为 null 时不设置 item-name（如 blank 隐形物品）。
     *  CE 的 item-name 支持文本富文本格式，翻译键须用 <lang:key> 引用，
     *  <!i> 去斜体、<black> 黑色字体（与原版浅色羊皮纸背景对比清晰）。 */
    private void writeGuiItem(Writer w, String id, String modelPath, String langKey) throws java.io.IOException {
        w.write(String.format("  immersive_melodies:gui_%s:\n", id));
        w.write("    material: paper\n");
        w.write("    data:\n");
        if (langKey != null) {
            w.write(String.format("      item-name: <!i><black><lang:%s>\n", langKey));
        }
        w.write("      max-stack-size: 1\n");
        w.write("    model:\n");
        w.write("      type: minecraft:model\n");
        w.write(String.format("      path: %s\n", modelPath));
    }
}

